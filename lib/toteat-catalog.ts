export const TOTEAT_CATALOG_BY_CODE = new Map(
  RAW_CATALOG.map(item => [normalizeCode(item.codigo), item]),
);

export function getToteatCatalogItem(code: string | null | undefined) {
  if (!code) return null;
  return TOTEAT_CATALOG_BY_CODE.get(normalizeCode(code)) ?? null;
}

export function getToteatCanonicalName(code: string | null | undefined, fallback: string) {
  return getToteatCatalogItem(code)?.nombre_canonico ?? fallback;
}

export function getToteatCanonicalCategory(code: string | null | undefined, fallback: string | null) {
  return getToteatCatalogItem(code)?.categoria ?? fallback;
}

function normalizeCode(value: string) {
  return value.trim().toUpperCase();
}
