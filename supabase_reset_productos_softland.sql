DO $$
DECLARE codigos_ficticios TEXT[] := ARRAY['0301006','0501001','0501002','0601001','0601002','0701001','0701002'];
        c TEXT;
BEGIN
  FOREACH c IN ARRAY codigos_ficticios LOOP
    BEGIN
      DELETE FROM productos WHERE codigo = c;
      RAISE NOTICE 'Eliminado: %', c;
    EXCEPTION WHEN foreign_key_violation THEN
      RAISE NOTICE 'No se pudo eliminar % — tiene referencias en otras tablas. Marcar como inactivo.', c;
      UPDATE productos SET activo = false WHERE codigo = c;
    END;
  END LOOP;
END $$;

